export type AgentOperationName = keyof typeof agentOperations;

export const agentOperationInputSchema = (
  definition: AgentOperationDefinition
) =>
  z
    .object({
      params: definition.params ?? agentEmptyRequestSchema.optional(),
      query: definition.query ?? agentEmptyRequestSchema.optional(),
      body: definition.body ?? agentEmptyRequestSchema.optional(),
      idempotencyKey: definition.idempotent
        ? agentIdempotencyKeySchema
        : agentIdempotencyKeySchema.optional(),
    })
    .strict();

export const agentMcpOperationNames = (
  Object.entries(agentOperations) as Array<
    [AgentOperationName, AgentOperationDefinition]
  >
)
  .filter(([, definition]) => definition.mcp)
  .map(([name]) => name);
