export type AgentOperationAuth =
  | "public"
  | "enrollment-token"
  | "agent"
  | "human-or-agent"
  | "human-admin"
  | "human-admin-2fa"
  | "platform-operator"
  | "provider";

export type AgentOperationDefinition = {
  method: "GET" | "POST" | "PATCH" | "PUT" | "DELETE";
  path: string;
  auth: AgentOperationAuth;
  capability?: AgentCapability;
  idempotent: boolean;
  summary: string;
  description?: string;
  params?: ZodType;
  query?: ZodType;
  body?: ZodType;
  response?: ZodType;
  responseKind?: "json" | "text" | "binary" | "empty";
  successStatus: number;
  mcp: boolean;
};

const operation = <T extends AgentOperationDefinition>(definition: T) =>
  definition;

